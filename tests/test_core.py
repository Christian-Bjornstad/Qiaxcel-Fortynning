import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
from qiaxcel.core import Peak, Sample, analyze, dilution, identify_assay, parse_pages


class RulesTests(unittest.TestCase):
    def test_thresholds(self):
        for rfu, expected in [(0, 'Ufortynnet'), (1499, 'Ufortynnet'),
                              (1500, '1:2'), (1999, '1:2'), (2000, '1:5'),
                              (3999, '1:5'), (4000, '1:10'), (6000, '1:10'),
                              (6001, '1:15 eller 1:20')]:
            with self.subTest(rfu=rfu):
                self.assertEqual(dilution(rfu), expected)
        for invalid in [-1, float('nan'), float('inf')]:
            with self.assertRaises(ValueError):
                dilution(invalid)

    def test_assays_are_not_inferred_from_peak_or_filename(self):
        for label, expected in [('KIT ex9 123', 'KIT exon 9'),
                                ('PDGFRa ex18 gDNA', 'PDGFRA exon 18'),
                                ('B-CAT', 'CTNNB1'), ('ABL B', 'ABL-B'),
                                ('TERT-IDH', None), ('IDH', None),
                                ('H3F3A', 'H3F3A'), ('ABLmut1PCR', None)]:
            self.assertEqual(identify_assay(label), expected, label)

    def test_no_factor_means_no_derived_rfu_or_dilution(self):
        row = analyze(Sample('a.pdf', 'A01', 'TERT', 1,
                             [Peak(192, 3.1, 2)]))
        self.assertIsNone(row.rfu)
        self.assertEqual(row.dilution, '')
        self.assertIn('RFU-skala', row.note)

    def test_selection_and_flags(self):
        sample = Sample('a.pdf', 'A01', 'TERT', 1,
                        [Peak(15, 9.0, 2), Peak(192, 3.1, 2), Peak(1000, 9, 2)])
        row = analyze(sample, factor=1000)
        self.assertEqual((row.peak.bp, row.rfu, row.dilution, row.status),
                         (192, 3100, '1:5', 'KLAR'))
        sample.peaks.append(Peak(200, 2.8, 2))
        self.assertEqual(analyze(sample, factor=1000).status, 'KONTROLL')
        sample.peaks = []
        row = analyze(sample, factor=1000)
        self.assertIsNone(row.rfu)
        self.assertEqual(row.dilution, '')

    def test_controls_and_boundary_are_not_clear(self):
        for label, value in [('TERT NTC', 3.1), ('NEG TERT', 3.1), ('TERT gDNA', 3.1), ('TERT', 1.51), ('TERT', 6.2)]:
            row = analyze(Sample('a.pdf', 'A01', label, 1,
                                 [Peak(192, value, 2)]), factor=1000)
            self.assertEqual(row.status, 'KONTROLL')


class ParserTests(unittest.TestCase):
    def test_header_carries_over_page_and_two_column_table(self):
        pages = [(1, 'Sample Header\nPosition: A1 Run Date: today\nSample Info: KIT ex9 gDNA\n'
                     'Result Table\nSize Height Size Height\n[bp] [RFU] [bp] [RFU]\n'
                     '1 15 1.44 2 282 2.68\n3 1000 1.59\nSample Header\n'
                     'Position: A2 Run Date: today\nSample Info: KIT ex9 patient'),
                 (2, 'Figure: 3\nResult Table\nSize Height Size Height\n[bp] [RFU] [bp] [RFU]\n'
                     '1 15 0.15 2 288 1.83\n3 1000 2.57\nGenerated by QIAxcel')]
        samples = parse_pages(pages, 'report.pdf')
        self.assertEqual(len(samples), 2)
        self.assertEqual(samples[0].position, 'A01')
        self.assertEqual([(p.bp, p.height) for p in samples[0].peaks], [(15, 1.44), (282, 2.68), (1000, 1.59)])
        self.assertEqual(samples[1].peaks[1].page, 2)
        self.assertEqual(samples[1].info, 'KIT ex9 patient')

    def test_unsupported_or_missing_table_not_silent_zero(self):
        rows = parse_pages([(1, 'Position: H12 Run Date: x\nSample Info: TERT\nResult Table\n'
                                'Size Area\n1 190 3.1')], 'a.pdf')
        self.assertFalse(rows[0].peaks)
        self.assertTrue(rows[0].issues)

    def test_size_only_table_preserves_bp_without_inventing_height(self):
        samples = parse_pages([(1, 'Position: A1 Run Date: x\nResult Table\nSize Size\n# #\n'
                                    '[bp] [bp]\n1 15 2 193\n3 1000')], 'old.pdf')
        self.assertEqual([p.bp for p in samples[0].peaks], [15, 193, 1000])
        self.assertTrue(all(p.height is None for p in samples[0].peaks))
        self.assertIn('mangler Height', '; '.join(samples[0].issues))


if __name__ == '__main__':
    unittest.main()
